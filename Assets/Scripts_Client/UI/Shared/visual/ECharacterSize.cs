// 캐릭터 크기 등급 — 슬롯 무대에서 대상(산업 오브젝트)과 견준 몸집. 그림 결과 SO('CharacterVisual')가 갖는다.
//
// ※ 값은 에셋에 정수로 저장된다 — 뒤에만 추가하고 번호를 바꾸지 않는다.
public enum ECharacterSize
{
    None   = 0, // 아직 정하지 않음 — 다음 굽기가 레시피 템플릿으로 채운다
    Small  = 1, // 소형 — 박쥐·쥐·슬라임. 대상과 비슷하거나 작다
    Medium = 2, // 중형 — 사람 크기
    Large  = 3, // 대형 — 골렘·사신. 큰 대상과 비슷하다
}
